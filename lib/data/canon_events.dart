/// 原著剧情节点库（离线模式事件源）。
///
/// 【与 event_anchors.dart 的分工——别把两者混为一谈】
///
/// | 维度 | `EventAnchor` | `CanonEvent`（本文件） |
/// | --- | --- | --- |
/// | 性质 | **学年日历骨架**：每年按月份复现 | **原著时间线**：七部小说的一次性大事 |
/// | 例子 | 开学宴、万圣节、期末考、圣诞 | 密室开启、三强争霸、天文塔之夜 |
/// | 触发键 | `月份 + 年级 + 时代` | `年份 + 月份 + 时代` |
/// | 复现 | 每个学年可再触发一次（`@年级` 后缀） | **全域仅一次**（`canon_` 前缀） |
/// | 消费者 | `_checkEventAnchors`（AI 与离线共用） | `_runOfflineQuickTurn`（离线叙事拼装） |
///
/// 为什么要单独建一张表而不是往 `EventAnchor` 里塞：`EventAnchor` 的
/// `fixedOnlyOnce` 语义是「每学年一次」，而原著大事是「整个存档一次」。
/// 混在一起会让 1991 年发生过的密室事件在 1992 年又冒出来。
///
/// 【平行世界原则——本文件最容易犯的错】
/// 玩家是**原创角色**，不是哈利。原著事件必须写成「发生在你周围」，
/// 不能让玩家成为哈利。这条约束由 `test/canon_events_test.dart` 里的
/// 禁用措辞扫描守住（见该文件 `_forbiddenProtagonistPhrases`）。
/// 写法对照：
///   ❌ 「你在密室里举剑刺向蛇怪」      —— 玩家成了哈利
///   ✅ 「学校里流传着石化事件的消息，走廊巡逻加倍」 —— 事件在周围发生
///
/// 【版权说明】本文件只描述**剧情节点与氛围**，不抄录原著原文句子。
library;

/// 一条原著剧情节点。
class CanonEvent {
  final String id;

  /// 原著故事内年份（1991 = 哈利入学那年）。
  final int year;

  /// 触发月份（1-12）。
  final int month;

  /// 玩家需在的年级；null = 不限年级。
  ///
  /// 用途：有些事件对所有在校生都构成背景（如三强争霸全校围观），
  /// 有些只对特定年级有直接关联。
  final int? grade;

  /// 适用时代（`EraDef.eraKey`）。目前原著主线只有子世代。
  final List<String> eras;

  /// 标题（通知栏与存档记录用）。
  final String title;

  /// 注入给叙事的指令。
  ///
  /// 写作要求：
  ///   1. 旁观者视角（"你听说/你注意到/学校因此…"），禁止让玩家成为事件主角；
  ///   2. 2~3 句，具体到可被叙事 AI 或离线拼装直接使用；
  ///   3. 提供**玩家可行动的接口**（如"你可以打听消息/避开某处"），
  ///      否则离线模式下玩家只能读不能动。
  final String directive;

  /// 出处标注（如「魔法石」），便于溯源与维护。
  final String bookRef;

  // ================================================================
  // 与长期记忆 / 图鉴的接线（v2）
  // ================================================================
  //
  // 【为什么挂在 CanonEvent 上而不是逐条写进 StoryStepDef】
  // 原著节点有 102 条且全部按 (year, month) 精确对位；而"这件事值得写进
  // 长期记忆"是**节点自身的性质**——密室被打开、伏地魔回归，无论哪个
  // 剧情步讲述它，都该沉淀下来。写在节点上是一次声明、全局生效；
  // 写进步骤里则要在 102 个步上各抄一遍，且换步引用时必然漏。
  //
  // 【为什么是可选的】不是每个节点都够格进持久层（"对角巷采购日"
  // 就没有长期记忆价值）。null = 不写，保持默认行为。

  /// 沉进长期记忆 T3 世界大事层的描述；null = 不写。
  ///
  /// 写成"纯事实、60 字以内"（与 `WorldEventRecord.description` 的口径
  /// 一致），不要写第二人称——它会被注入给叙事 AI 当**客观事实**用。
  final String? worldEvent;

  /// 本节点重要度（1~10）。仅当 [worldEvent] 非空时有意义。
  ///
  /// 默认 7（重要事件结论）。原著主线里真正该永不淘汰的少数节点
  /// （密室、三强争霸、伏地魔回归、邓布利多之死）填 9，
  /// 走到 `kPersistentFactImportance` 的持久层。
  final int worldEventImportance;

  /// 本节点**开启**的悬念（`'id|描述'`）；null = 不开启。
  ///
  /// 只在"这件事悬而未决"时才填——谜团、威胁、没答案的问题。
  /// 已了结的事件不填（那属于 [worldEvent]）。
  final String? openLoop;

  /// 本节点**了结**的悬念 id（对应先前某个 [openLoop] 开的 id）。
  ///
  /// 【为什么是列表而不是单值】原著里不少节点一口气收束多条线索。
  /// 《魔法石》学年末同时回答了"713 号金库里是什么"（开于 7 月古灵阁）
  /// 与"那面镜子照见的是什么"（开于 12 月）；用单值就只能关一条，
  /// 另一条会永远挂在 T1「未完结事项」里，直到 `staleLoopsToDrop`
  /// 按超期静默丢弃——玩家看到一条没有下文的悬念，AI 把它当成仍在
  /// 推进的伏笔。实测七部曲里 4 条悬念正是这么悬着的（第九次审查 P1）。
  final List<String> closeLoops;

  /// 本节点解锁的 CG id（如 `'CG-002'`）；null = 不牵 CG。
  final String? unlockCg;

  const CanonEvent({
    required this.id,
    required this.year,
    required this.month,
    this.grade,
    this.eras = const ['harry_same'],
    required this.title,
    required this.directive,
    required this.bookRef,
    this.worldEvent,
    this.worldEventImportance = 7,
    this.openLoop,
    this.closeLoops = const [],
    this.unlockCg,
  });
}

