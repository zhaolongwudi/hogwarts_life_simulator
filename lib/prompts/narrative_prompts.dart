/// [profile] 已经按"｜"合并成一行字符串，[wandDetail] 如"枫木·凤凰羽毛·11英寸"。
String buildOpeningNarrativePrompt({
  required String profileLine,
  required String startPoint,
  required String wandDetail,
  required String wandSourceLine,
}) => '''【开场叙事】J.K.罗琳风格，3+感官细节。

【玩家资料】
$profileLine

【起始场景】$startPoint

【魔杖硬设定·必须严格遵守】
- $wandSourceLine
- 若开场节点为 letter 或更早，叙事中可以写"你还带着前几天在对角巷奥利凡德购得的魔杖匣子"，不必展开采购剧情本身，但必须明确其来源为奥利凡德。
- 魔杖细节必须为"$wandDetail"，不能更改木材/杖芯/长度。

【要求】600-800字精练叙事，📅时间戳开头，自然融入魔杖/宠物/血统，体现性格，直奔主题。分3-5段用空行分隔，感官细节融入动作，对话简练，拒绝空洞堆砌。

【格式】
【时间戳】📅 日期
【地点】具体位置
（正文）
【可选行动】A/B/C（具体动作）
【自由行动】''';

